import { spawnSync } from 'node:child_process'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import openapiTS, { astToString } from 'openapi-typescript'

const root = resolve(import.meta.dirname, '..')
const result = spawnSync('go', ['-C', 'apps/api', 'run', './cmd/openapi'], { cwd: root, encoding: 'utf8', windowsHide: true })
if (result.error || result.status !== 0) throw new Error('OpenAPI generation failed; run go -C apps/api run ./cmd/openapi to inspect the error')
const schema = JSON.parse(result.stdout)
const types = astToString(await openapiTS(schema))
const files = new Map([
  [resolve(root, 'packages/api-client/openapi.json'), `${JSON.stringify(schema, null, 2)}\n`],
  [resolve(root, 'packages/api-client/src/schema.ts'), `// Code generated by openapi-typescript. DO NOT EDIT.\n${types}`],
])
await mkdir(resolve(root, 'packages/api-client/src'), { recursive: true })
for (const [path, content] of files) {
  if (process.argv.includes('--check')) {
    if ((await readFile(path, 'utf8')).replaceAll('\r\n', '\n') !== content.replaceAll('\r\n', '\n')) throw new Error('Generated API contract is stale; run pnpm api:generate:client')
  } else await writeFile(path, content)
}
process.stdout.write(process.argv.includes('--check') ? 'API contract is up to date.\n' : 'Generated API contract and TypeScript types.\n')
