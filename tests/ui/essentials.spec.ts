import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/iframe.html?id=overview-essentials--default&viewMode=story')
  await expect(page.getByRole('heading', { name: '常用组件工作台' })).toBeVisible()
})

test('password visibility, OTP entry and slider keyboard', async ({ page }) => {
  const password = page.getByLabel('演示密码', { exact: true })
  await password.fill('example-password')
  await expect(password).toHaveAttribute('type', 'password')
  await page.getByRole('button', { name: '显示密码' }).click()
  await expect(password).toHaveAttribute('type', 'text')
  await expect(password).toHaveValue('example-password')
  await page.getByRole('button', { name: '隐藏密码' }).click()
  await expect(password).toHaveAttribute('type', 'password')
  await page.getByRole('textbox', { name: '邮箱验证码 第 1 位', exact: true }).focus()
  await page.keyboard.type('012345')
  for (let index = 0; index < 6; index++) {
    await expect(page.getByRole('textbox', { name: `邮箱验证码 第 ${index + 1} 位`, exact: true })).toHaveValue(String(index))
  }
  const slider = page.getByRole('slider', { name: '预览音量', exact: true })
  await slider.focus()
  await page.keyboard.press('ArrowRight')
  await expect(slider).toHaveAttribute('aria-valuenow', '51')
  await page.keyboard.press('Home')
  await expect(slider).toHaveAttribute('aria-valuenow', '0')
})

test('popover, drawer and toast support dismissal', async ({ page }) => {
  const filter = page.getByRole('button', { name: '打开筛选' })
  await filter.click()
  await expect(page.getByRole('dialog', { name: '打开筛选' })).toContainText('筛选条件')
  await page.keyboard.press('Escape')
  await expect(filter).toBeFocused()
  const trigger = page.getByRole('button', { name: '打开详情抽屉' })
  await trigger.click()
  const drawer = page.getByRole('dialog', { name: '应用详情' })
  await expect(drawer).toHaveAccessibleDescription('右侧抽屉保留当前页面上下文。')
  await drawer.getByRole('button', { name: '完成' }).click()
  await expect(drawer).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await page.getByRole('button', { name: '显示保存通知' }).click()
  await expect(page.getByText('设置已保存', { exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: '关闭通知' }).click()
  await expect(page.getByRole('button', { name: '关闭通知' })).toHaveCount(0)
})

test('accordion, removable tags and external sorting keep semantics', async ({ page }) => {
  const question = page.getByRole('button', { name: '什么是统一账号？' })
  await question.click()
  await expect(question).toHaveAttribute('aria-expanded', 'true')
  await expect(page.getByText('使用同一身份访问已接入的应用，每个应用独立管理自己的业务权限。')).toBeVisible()
  await question.click()
  await expect(question).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('button', { name: '暂不可用的帮助' })).toBeDisabled()
  await page.getByRole('button', { name: '移除 Nuxt', exact: true }).click()
  await expect(page.getByRole('button', { name: '移除 Nuxt', exact: true })).toHaveCount(0)
  const table = page.getByRole('table', { name: '示例应用列表' })
  await table.getByRole('button', { name: '应用名称' }).click()
  await expect(table.getByRole('columnheader', { name: '应用名称' })).toHaveAttribute('aria-sort', 'descending')
  await expect(table.getByRole('row').nth(1)).toContainText('开发预览')
  await expect(page.getByRole('progressbar', { name: '资料完善程度' })).toHaveAttribute('aria-valuenow', '35')
  await page.getByRole('button', { name: '更新进度' }).click()
  await expect(page.getByRole('progressbar', { name: '资料完善程度' })).toHaveAttribute('aria-valuenow', '55')
})

test('searchable selection filters, handles empty results and supports keyboard', async ({ page }) => {
  const search = page.getByRole('combobox', { name: '搜索应用', exact: true })
  await search.fill('Gallery')
  await expect(page.getByRole('option', { name: 'Personal Gallery' })).toBeVisible()
  await expect(page.getByRole('option', { name: 'Moetopia Community' })).toHaveCount(0)
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(search).toHaveValue('Personal Gallery')
  await search.fill('不存在的应用')
  await expect(page.getByText('没有匹配的选项', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(search).toBeFocused()
})

test('number field enforces bounds and native date preserves a date string', async ({ page }) => {
  const quantity = page.getByRole('spinbutton', { name: '每页条目数' })
  await quantity.focus()
  await page.keyboard.press('ArrowUp')
  await expect(quantity).toHaveValue('11')
  await quantity.fill('100')
  await quantity.blur()
  await expect(page.getByRole('button', { name: '增加', exact: true })).toBeDisabled()
  const date = page.getByLabel('生效日期', { exact: true })
  await date.fill('2026-10-18')
  await expect(date).toHaveValue('2026-10-18')
  await expect(date).toHaveAttribute('min', '2026-01-01')
})

test('file selection and clearing stay local, checkbox group updates independently', async ({ page }) => {
  const input = page.getByLabel('选择应用图标', { exact: true })
  await input.setInputFiles({ name: 'demo-icon.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"/>') })
  await expect(page.getByText('demo-icon.svg', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '清除已选文件', exact: true }).click()
  expect(await input.evaluate(element => (element as HTMLInputElement).files?.length)).toBe(0)
  const group = page.getByRole('group', { name: '通知分类' })
  await expect(group.getByRole('checkbox', { name: '安全提醒' })).toBeChecked()
  await group.getByRole('checkbox', { name: '社区动态' }).click()
  await expect(group.getByRole('checkbox', { name: '社区动态' })).toBeChecked()
  await expect(group.getByRole('checkbox', { name: '安全提醒' })).toBeChecked()
  await expect(group.getByRole('checkbox', { name: '其他通知' })).toBeDisabled()
})

test('scroll region is keyboard reachable and avatar overflow is named', async ({ page }) => {
  const region = page.getByRole('region', { name: '示例活动记录' })
  await region.focus()
  await page.keyboard.press('PageDown')
  await expect.poll(() => region.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
  await expect(page.getByRole('group', { name: '应用协作者' }).getByRole('img', { name: '另有 2 位成员' })).toBeVisible()
})

for (const theme of ['light', 'dark']) {
  test(`${theme} common components fit a narrow viewport`, async ({ page }) => {
    await page.setViewportSize({ width: 375, height: 812 })
    await page.goto(`/iframe.html?id=overview-essentials--default&viewMode=story&globals=theme:${theme}`)
    await expect(page.getByRole('heading', { name: '常用组件工作台' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  })
}
