import { expect, type Page } from '@playwright/test'

export const verifyPortalUI = async (page: Page, management = false) => {
  await page.goto('http://127.0.0.1:54305/developer')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '使用 Moetopia 账号登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Moetopia user site', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '允许访问', exact: true }).click()
  await expect(page).toHaveURL('http://127.0.0.1:54305/developer/applications')
  await expect(page.getByRole('heading', { name: '我的应用', exact: true })).toBeVisible()
  if (management) {
  await page.getByRole('button', { name: '创建应用', exact: true }).first().click()
  const create = page.getByRole('dialog', { name: '创建应用' })
  await create.getByLabel('应用名称', { exact: true }).fill('Browser managed application')
  await create.getByLabel('回调地址 1', { exact: true }).fill('http://127.0.0.1:54310/callback')
  const createdResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/api/v1/developer/applications' && response.request().method() === 'POST')
  await create.getByRole('button', { name: '创建应用', exact: true }).click()
  expect((await createdResponse).status(), 'Application creation HTTP status').toBe(200)
  await expect(create).toHaveCount(0)
  await page.getByRole('link', { name: /^应用详情:/ }).click()
  await expect(page).toHaveURL(/\/developer\/applications\/[^/?]+$/)
  await expect(page.getByRole('heading', { level: 2, name: 'Browser managed application' })).toBeVisible()
  const applicationURL = page.url()
  const usageList = page.waitForResponse(response => new URL(response.url()).pathname === '/api/v1/developer/applications' && response.request().method() === 'GET', { timeout: 12000 })
  await page.goto('http://127.0.0.1:54305/developer/usage')
  const listed = await usageList
  expect(listed.status(), 'Usage application list HTTP status').toBe(200)
  expect(new URL(listed.url()).searchParams.has('cursor')).toBe(false)
  await expect(page.getByRole('figure')).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.goto(applicationURL)
  await expect(page.getByRole('heading', { level: 2, name: 'Browser managed application' })).toBeVisible()
  await page.getByRole('button', { name: '编辑应用', exact: true }).click()
  const edit = page.getByRole('dialog', { name: '编辑应用' })
  await edit.getByLabel('应用名称', { exact: true }).fill('Updated browser application')
  await edit.getByRole('button', { name: '保存草稿' }).click()
  await expect(page.getByRole('heading', { level: 2, name: 'Updated browser application' })).toBeVisible()
  await page.getByRole('button', { name: '编辑用户登录', exact: true }).click()
  const loginSettings = page.getByRole('dialog', { name: '编辑用户登录' })
  await loginSettings.getByRole('button', { name: '添加回调地址' }).click()
  await loginSettings.getByLabel('回调地址 2', { exact: true }).fill('http://127.0.0.1:54310/second-callback')
  await loginSettings.getByRole('checkbox', { name: '基本资料（profile）' }).check()
  await loginSettings.getByRole('button', { name: '保存草稿' }).click()
  await expect(loginSettings).toHaveCount(0)
  await expect(page.getByText('http://127.0.0.1:54310/second-callback', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '提交审核', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '确认操作' }).click()
  await expect(page.getByRole('button', { name: '编辑应用', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '停用应用', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '确认操作' }).click()
  await page.getByRole('button', { name: '删除应用', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '确认操作' }).click()
  await expect(page).toHaveURL('http://127.0.0.1:54305/developer/applications')
  await page.getByRole('button', { name: '你的账号', exact: true }).click()
  await page.getByRole('menuitem', { name: '个人资料', exact: true }).click()
  await page.getByLabel('个人简介', { exact: true }).fill('Browser profile update')
  await page.getByRole('button', { name: '保存修改' }).click()
  await expect(page.getByRole('alert')).toHaveText('已保存')
  await page.getByRole('button', { name: '你的账号', exact: true }).click()
  await page.getByRole('menuitem', { name: '安全设置', exact: true }).click()
  await expect(page.getByRole('heading', { name: '已授权记录', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '撤销授权', exact: true }).first()).toBeVisible()
  }
  await page.getByRole('button', { name: '你的账号', exact: true }).click()
  await page.getByRole('menuitem', { name: '登录会话', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('登录会话')
  await expect(page.getByRole('button', { name: '结束会话', exact: true })).toHaveCount(1)
  await page.reload()
  await expect(page.getByRole('button', { name: '结束会话', exact: true })).toHaveCount(1)
  await page.getByRole('button', { name: '你的账号', exact: true }).click()
  await page.getByRole('menuitem', { name: '退出登录', exact: true }).click()
  await expect(page).toHaveURL('http://127.0.0.1:54305/auth/logout')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('已退出用户站')
  const portal = await page.context().request.get('http://127.0.0.1:54305/api/v1/portal/context')
  expect((await portal.json() as { authenticated: boolean }).authenticated).toBe(false)
  const identity = await page.context().request.get('http://127.0.0.1:54305/api/v1/account/context')
  expect((await identity.json() as { user?: unknown }).user).toBeTruthy()
}
