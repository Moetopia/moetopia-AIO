test('dialog locking preserves the page geometry without a second scrollbar compensation', async ({ page }) => {
  await mockPortal(page)
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(`${origin}/developer/applications`)
  await page.addStyleTag({ content: 'body { min-height: 200vh; }' })
  const geometry = () => page.evaluate(() => ({ body: document.body.getBoundingClientRect().width, padding: getComputedStyle(document.body).paddingRight, nav: document.querySelector('.moe-navbar')!.getBoundingClientRect().x, gutter: innerWidth - document.documentElement.clientWidth }))
  const before = await geometry()
  expect(before.gutter).toBeGreaterThan(0)
  await page.getByRole('button', { name: '创建应用', exact: true }).first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  expect((await geometry()).padding).toBe('0px')
  expect((await geometry()).body).toBe(before.body)
  expect((await geometry()).nav).toBe(before.nav)
  expect(await page.evaluate(() => getComputedStyle(document.body).overflow)).toBe('hidden')
  expect(await page.evaluate(() => getComputedStyle(document.documentElement).scrollbarWidth)).toBe('thin')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect((await geometry()).body).toBe(before.body)
  await page.setViewportSize({ width: 375, height: 700 })
  await page.getByRole('button', { name: '创建应用', exact: true }).first().click()
  expect(await page.getByRole('dialog').evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('application cards have real padding and switch from two columns to one on mobile', async ({ page }) => {
  await mockPortal(page)
  await page.route('**/api/v1/developer/applications', route => route.fulfill({ json: { items: [fixture(), { ...fixture(), id: 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb' }], next_cursor: '' } }))
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(`${origin}/developer/applications`)
  const cards = page.locator('.moe-resource-card')
  await expect(cards).toHaveCount(2)
  await expect(cards.first()).toHaveCSS('padding-left', '20px')
  await expect(cards.first()).toHaveCSS('padding-right', '20px')
  expect((await cards.nth(0).boundingBox())!.y).toBe((await cards.nth(1).boundingBox())!.y)
  await page.setViewportSize({ width: 375, height: 900 })
  expect((await cards.nth(1).boundingBox())!.y).toBeGreaterThan((await cards.nth(0).boundingBox())!.y)
})

test('reference detail composition keeps identity and user-login editing separate', async ({ page }) => {
  await mockPortal(page)
  let application = fixture()
  await mockApplicationReads(page, () => application)
  await page.route(`**/api/v1/developer/applications/${id}`, route => route.fulfill({ json: application }))
  await page.route(`**/api/v1/developer/applications/${id}/draft`, route => {
    const body = route.request().postDataJSON()
    expect(body.revision).toBe(application.revision)
    application = { ...application, revision: application.revision + 1, latest: { ...application.latest, config: body.config } }
    return route.fulfill({ json: application })
  })
  await page.goto(`${origin}/developer/applications/${id}`)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('应用详情')
  const summary = page.locator('.moe-resource-summary')
  await expect(summary.getByRole('heading', { level: 2 })).toHaveText('Community app')
  await expect(summary.getByRole('button', { name: '编辑应用', exact: true })).toBeVisible()
  await expect(summary.getByRole('button', { name: '删除应用', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '编辑用户登录', exact: true }).click()
  const login = page.getByRole('dialog', { name: '编辑用户登录' })
  await expect(login.getByLabel('应用名称')).toHaveCount(0)
  await login.getByRole('button', { name: '添加回调地址' }).click()
  await login.getByLabel('回调地址 2', { exact: true }).fill('https://example.com/second')
  await login.getByRole('checkbox', { name: '邮箱（email）' }).check()
  await expect(login.locator('.moe-checkbox-group')).toHaveAttribute('data-variant', 'cards')
  await login.getByRole('button', { name: '保存草稿' }).click()
  await expect(login).toHaveCount(0)
  expect(application.latest.config.redirect_uris).toEqual(['https://example.com/callback', 'https://example.com/second'])
  expect(application.latest.config.scopes).toEqual(['openid', 'profile', 'email'])
  expect(application.latest.config.name).toBe('Community app')
  await page.getByRole('button', { name: '编辑应用', exact: true }).click()
  const identity = page.getByRole('dialog', { name: '编辑应用' })
  await expect(identity.getByLabel('回调地址 1')).toHaveCount(0)
  await identity.getByLabel('应用名称', { exact: true }).fill('Edited identity')
  await identity.getByRole('button', { name: '保存草稿' }).click()
  expect(application.latest.config.redirect_uris).toHaveLength(2)
  await expect(summary.getByRole('heading', { level: 2 })).toHaveText('Edited identity')
})

test('developer document search supports Ctrl K, filtering and keyboard navigation', async ({ page }) => {
  await mockPortal(page)
  await page.goto(`${origin}/developer`)
  await page.keyboard.press('Control+k')
  const dialog = page.getByRole('dialog', { name: '搜索文档', exact: true })
  await expect(dialog).toBeVisible()
  const search = dialog.getByRole('searchbox', { name: '搜索文档' })
  await expect(search).toBeFocused()
  await search.fill('no match')
  await expect(dialog.getByRole('status')).toHaveText('没有匹配的页面')
  await search.fill('端点')
  await search.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(`${origin}/developer/docs/endpoints`)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('端点参考')
  await expect(dialog).toHaveCount(0)
})

test('deleting an enabled app explicitly confirms suspension and uses its resulting revision', async ({ page }) => {
  await mockPortal(page)
  let application = fixture()
  await mockApplicationReads(page, () => application)
  const operations: string[] = []
  await page.route(`**/api/v1/developer/applications/${id}`, route => {
    if (route.request().method() === 'DELETE') { expect(route.request().postDataJSON().revision).toBe(2); operations.push('delete'); return route.fulfill({ status: 204 }) }
    return route.fulfill({ json: application })
  })
  await page.route(`**/api/v1/developer/applications/${id}/availability`, route => {
    expect(route.request().postDataJSON()).toEqual({ revision: 1, enabled: false })
    operations.push('disable'); application = { ...application, enabled: false, revision: 2 }
    return route.fulfill({ json: application })
  })
  await page.goto(`${origin}/developer/applications/${id}`)
  await page.getByRole('button', { name: '删除应用', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('将先停用应用并撤销既有授权')
  await page.getByRole('dialog').getByRole('button', { name: '停用并删除', exact: true }).click()
  await expect(page).toHaveURL(`${origin}/developer/applications`)
  expect(operations).toEqual(['disable', 'delete'])
})
