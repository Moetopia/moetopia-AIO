test('POST logout tests submit a browser form instead of changing the protocol method', async ({ page }) => {
  await page.addInitScript(() => {
    HTMLFormElement.prototype.submit = function () { (window as unknown as { submitted: { method: string; action: string } }).submitted = { method: this.method, action: this.action } }
  })
  await page.goto(origin + '/developer/docs/api/oauth-logout-post')
  await page.locator('#test').getByLabel('client_id · body · Public', { exact: true }).fill('example-client')
  await page.locator('#test').getByRole('button', { name: '打开测试窗口', exact: true }).click()
  const submitted = await page.evaluate(() => (window as unknown as { submitted: { method: string; action: string } }).submitted)
  expect(submitted.method).toBe('post')
  expect(new URL(submitted.action).pathname).toBe('/oauth/logout')
  expect(new URL(submitted.action).search).toBe('')
})

test('business tests use the matching Cookie context and CSRF without automatic retries', async ({ page }) => {
  await page.context().addCookies([{ name: 'example_cookie', value: 'example-only-cookie', url: origin }])
  await page.route('**/api/v1/portal/context', route => route.fulfill({ json: { csrf_token: 'example-csrf' } }))
  let writes = 0
  await page.route('**/api/v1/developer/applications', route => {
    writes++
    expect(route.request().headers()['x-moetopia-csrf']).toBe('example-csrf')
    expect(route.request().headers().cookie).toContain('example_cookie=example-only-cookie')
    expect(route.request().postDataJSON()).toEqual({ public: true, config: {} })
    return route.fulfill({ status: 422, json: { code: 'application_invalid' } })
  })
  await page.goto(origin + '/developer/docs/api/post-api-v1-developer-applications')
  await page.locator('#test').getByLabel('JSON 请求体', { exact: true }).fill('{"public":true,"config":{}}')
  await page.locator('#test').getByRole('button', { name: '发送请求', exact: true }).click()
  await expect(page.locator('#test')).toContainText('HTTP 422')
  expect(writes).toBe(1)
})

test('a pending request can be canceled and cleared without retaining its credentials', async ({ page }) => {
  await page.route('**/oauth/userinfo', () => {})
  await page.goto(origin + '/developer/docs/api/oauth-userinfo')
  const panel = page.locator('#test')
  await panel.getByLabel('Access token', { exact: true }).fill('example-only-pending')
  await panel.getByRole('button', { name: '发送请求', exact: true }).click()
  await panel.getByRole('button', { name: '停止等待', exact: true }).click()
  await expect(panel.getByRole('alert')).toContainText('请求未完成')
  await expect(panel.getByRole('button', { name: '发送请求', exact: true })).toBeEnabled()
  await panel.getByRole('button', { name: '清空测试数据', exact: true }).click()
  await expect(panel.getByLabel('Access token', { exact: true })).toHaveValue('')
  await expect(panel.getByRole('alert')).toHaveCount(0)
})
