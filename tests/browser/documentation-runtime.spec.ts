test('folder navigation retains branches and identifies the selected operation', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(origin + '/developer/docs/api/oauth-token')
  const sidebar = page.locator('.moe-docs-sidebar')
  const oauth = sidebar.getByRole('button', { name: /OAuth \/ OIDC/ })
  await expect(oauth).toHaveAttribute('aria-expanded', 'true')
  await expect(sidebar.locator('a[href="/developer/docs/api/oauth-token"]')).toHaveAttribute('aria-current', 'page')
  const admin = sidebar.getByRole('button', { name: /管理控制台/ })
  await admin.click()
  await sidebar.locator('a[href="/developer/docs/api/oauth-userinfo"]').click()
  await expect(page).toHaveURL(origin + '/developer/docs/api/oauth-userinfo')
  await expect(admin).toHaveAttribute('aria-expanded', 'true')
  await expect(sidebar.locator('a[href="/developer/docs/api/oauth-userinfo"]')).toHaveAttribute('aria-current', 'page')
  await oauth.click()
  await expect(sidebar.locator('a[href="/developer/docs/api/oauth-userinfo"]')).not.toBeVisible()
  await oauth.focus(); await page.keyboard.press('ArrowRight')
  await expect(sidebar.locator('a[href="/developer/docs/api/oauth-userinfo"]')).toBeVisible()
  await page.reload()
  await expect(sidebar.locator('a[href="/developer/docs/api/oauth-userinfo"]')).toHaveAttribute('aria-current', 'page')
})

test('guide tests send browser requests only after an explicit action', async ({ page }) => {
  let requests = 0
  await page.route('**/.well-known/openid-configuration', route => { requests++; return route.fulfill({ json: { issuer: 'https://example.com' } }) })
  await page.goto(origin + '/developer/docs')
  expect(requests).toBe(0)
  await page.locator('#test').getByRole('button', { name: '发送请求', exact: true }).click()
  await expect(page.locator('#test')).toContainText('HTTP 200')
  await expect(page.locator('#test')).toContainText('https://example.com')
  expect(requests).toBe(1)
})

test('public token tests encode form input, display errors and clear transient credentials', async ({ page }) => {
  let requests = 0
  await page.route('**/oauth/token', route => {
    requests++
    const body = new URLSearchParams(route.request().postData() ?? '')
    expect(body.get('grant_type')).toBe('authorization_code')
    expect(body.get('client_id')).toBe('example-public-client')
    expect(body.get('code_verifier')).toBe('example-only-verifier')
    expect(route.request().headers()['content-type']).toBe('application/x-www-form-urlencoded')
    return route.fulfill({ status: 400, json: { error: 'invalid_grant' } })
  })
  await page.goto(origin + '/developer/docs/api/oauth-token')
  const panel = page.locator('#test')
  await panel.getByLabel('client_id · body · Public', { exact: true }).fill('example-public-client')
  await panel.getByLabel('code_verifier · body', { exact: true }).fill('example-only-verifier')
  await panel.getByLabel('code · body', { exact: true }).fill('example-only-code')
  await panel.getByRole('button', { name: '发送请求', exact: true }).click()
  await expect(panel).toContainText('HTTP 400')
  await expect(panel).toContainText('invalid_grant')
  expect(requests).toBe(1)
  expect(await page.evaluate(() => JSON.stringify({ ...localStorage, ...sessionStorage }))).not.toContain('example-only')
  await panel.getByRole('button', { name: '清空测试数据' }).click()
  await expect(panel.getByLabel('code_verifier · body', { exact: true })).toHaveValue('')
  await expect(panel).not.toContainText('invalid_grant')
})

test('Bearer tests omit Cookies and backend-secret endpoints do not collect a secret', async ({ page }) => {
  await page.context().addCookies([{ name: 'example_cookie', value: 'example-only-cookie', url: origin }])
  await page.route('**/oauth/userinfo', route => {
    expect(route.request().headers().authorization).toBe('Bearer example-only-access')
    expect(route.request().headers().cookie).toBeUndefined()
    return route.fulfill({ json: { sub: 'example-subject' } })
  })
  await page.goto(origin + '/developer/docs/api/oauth-userinfo')
  await page.locator('#test').getByLabel('Access token', { exact: true }).fill('example-only-access')
  await page.locator('#test').getByRole('button', { name: '发送请求', exact: true }).click()
  await expect(page.locator('#test')).toContainText('example-subject')
  await page.evaluate(() => window.dispatchEvent(new PageTransitionEvent('pagehide')))
  await expect(page.locator('#test').getByLabel('Access token', { exact: true })).toHaveValue('')
  await expect(page.locator('#test')).not.toContainText('example-subject')
  await page.goto(origin + '/developer/docs/api/oauth-introspect')
  await expect(page.locator('#test').getByRole('button', { name: '发送请求', exact: true })).toBeDisabled()
  await expect(page.locator('#test').getByRole('textbox')).toHaveCount(0)
  await expect(page.locator('#test')).toContainText('终端测试模板')
  await page.goto(origin + '/developer/docs/api/oauth-userinfo')
  await expect(page.locator('#test').getByLabel('Access token', { exact: true })).toHaveValue('')
})

test('PKCE generation opens authorization explicitly instead of fetching redirects', async ({ page }) => {
  await page.addInitScript(() => { window.open = url => { (window as unknown as { opened: string }).opened = String(url); return null } })
  await page.goto(origin + '/developer/docs/api/oauth-authorize')
  const panel = page.locator('#test')
  await panel.getByLabel('client_id · query · Public', { exact: true }).fill('example-client')
  await panel.getByLabel('redirect_uri · query', { exact: true }).fill('https://example.com/callback')
  await panel.getByRole('button', { name: '生成 state / nonce / PKCE', exact: true }).click()
  await expect(panel.getByLabel('code_challenge · query', { exact: true })).toHaveValue(/^[\w-]{43}$/)
  await panel.getByRole('button', { name: '打开测试窗口', exact: true }).click()
  const opened = await page.evaluate(() => (window as unknown as { opened: string }).opened)
  expect(new URL(opened, origin).pathname).toBe('/oauth/authorize')
  expect(new URL(opened, origin).searchParams.get('code_challenge_method')).toBe('S256')
  await panel.getByRole('button', { name: '清空测试数据' }).click()
  await expect(panel.locator('pre')).toHaveCount(0)
})

